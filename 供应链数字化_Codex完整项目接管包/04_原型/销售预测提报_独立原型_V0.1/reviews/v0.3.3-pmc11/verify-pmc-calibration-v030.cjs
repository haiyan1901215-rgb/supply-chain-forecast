const assert = require('node:assert/strict');
const model = require('./forecast-batch-model.js');
const groups = [{ parent: 'P', market: 'US', account: 'S', children: [{ id: 'A', asin: 'A', base: 10 }, { id: 'B', asin: 'B', base: 10 }] }];
const services = { groups, forecastAt: child => ({ ai: child.base, final: child.base }), actualAt: child => child.base };
const storage = { value: null, getItem() { return this.value; }, setItem(key, value) { this.value = value; } };
const store = model.createStore(services, storage);
const id = store.getCurrent().id;
store.confirmRelations(id); store.confirmSplit(id); store.generateForecast(id);
const initial = store.getCurrent(), parent = initial.parentForecastResults[0];
const dates = Object.keys(parent.daily);
store.calibrateBaseline(id, 'parent', parent.key, { mode: 'daily', value: 30, date: dates[4], note: '测试指定日' }, '单日校准');
let batch = store.getCurrent();
assert.equal(batch.parentForecastResults[0].baselineDaily[dates[4]], 30);
assert.equal(batch.parentForecastResults[0].baselineDaily[dates[0]], 20);
assert.equal(batch.calibrations.parent[parent.key].note, '测试指定日');
store.recalculate(id, '保留重算');
assert.equal(store.getCurrent().parentForecastResults[0].baselineDaily[dates[4]], 30);
store.recalculate(id, '清除重算', { clearCalibration: true });
assert.equal(store.getCurrent().parentForecastResults[0].baselineDaily[dates[4]], 20);
assert.equal(store.getCurrent().resultSnapshots[0].version, initial.activeResultVersion);
const beforePreview = store.getCurrent();
const preview = store.previewShares(id, parent.key, { A: 6000, B: 4000 });
assert.deepEqual(store.getCurrent(), beforePreview, '影响预览不能改动草稿/快照/审计');
assert.deepEqual(preview.map(row => row.delta), [180, -180]);
const splitVersion = beforePreview.splitRuleSnapshot.version;
store.adjustShares(id, parent.key, { A: 6000, B: 4000 }, '尺码结构变化');
batch = store.getCurrent();
assert.notEqual(batch.splitRuleSnapshot.version, splitVersion);
assert.equal(batch.childForecastResults[0].dailyFinalForecast[dates[0]], 12);
assert.throws(() => store.adjustShares(id, parent.key, { A: 6000, B: 3900 }, '不平'), /100%/);
const oldParameter = batch.parameterSnapshot.version;
store.updateParameters(id, { historyShareWindow: 60 }, '新窗口');
assert.equal(store.getCurrent().parameterSnapshot.version, oldParameter);
const pending = store.getCurrent().pendingParameterSnapshot.version;
store.recalculate(id, '应用参数', { applyPendingParameters: true });
assert.equal(store.getCurrent().parameterSnapshot.version, pending);
assert.equal(store.contract.getSnapshot(id).resultSnapshots.at(-1).parameterVersion, pending);
store.confirmForecast(id);
const corrupted = JSON.parse(storage.value);
const raw = corrupted.batches.find(item => item.id === id);
raw.childForecastResults[0].dailyFinalForecast[dates[0]] += 1;
raw.childForecastResults[0].dailyFinalForecast[dates[1]] -= 1;
storage.value = JSON.stringify(corrupted);
const broken = model.createStore(services, storage);
assert.equal(broken.validateForecast(id).passed, false, '整期合计相同也必须阻断逐日不平');
assert.throws(() => broken.publishWindow(id, raw.submissionWindow), /发布检查/);
console.log('V0.3.30 daily calibration, recompute options, share impact, versions and publish gates passed');
