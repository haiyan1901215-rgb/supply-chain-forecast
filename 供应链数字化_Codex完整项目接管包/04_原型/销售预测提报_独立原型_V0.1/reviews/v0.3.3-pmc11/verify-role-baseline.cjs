const assert = require('node:assert/strict');
const model = require('./forecast-batch-model.js');
const values = require('./forecast-ledger-values.js');
const groups = [{ parent: 'PARENT', market: 'US', account: 'SHOP', owner: '销售', name: '样品', typeCode: 'F10', children: [{ id: 'C1', asin: 'CHILD1', base: 12 }, { id: 'C2', asin: 'CHILD2', base: 8 }] }];
const store = model.createStore({ groups, forecastAt: c => ({ ai: c.base, final: c.base }), actualAt: c => c.base }, null);
let batch = store.getCurrent();
const id = batch.id, parent = batch.parentForecastResults[0], child = batch.childForecastResults[0], date = batch.forecastStartDate;
store.confirmRelations(id); store.confirmSplit(id);
const original = child.dailyRuleForecast[date];
store.calibrateBaseline(id, 'parent', parent.key, { mode: 'adu', value: 30 }, '父体广告校准');
batch = store.getCurrent();
assert.equal(batch.parentForecastResults[0].daily[date], 20, 'system pool remains unchanged');
assert.equal(batch.parentForecastResults[0].baselineDaily[date], 30);
assert.equal(batch.childForecastResults.reduce((s, r) => s + r.dailyFinalForecast[date], 0), 30);
store.generateForecast(id);
const firstSnapshot = store.contract.getSnapshot(id);
const day = store.contract.getDailyForecast(id, child.childId, date);
assert.equal(day.systemForecast, original);
assert.equal(day.pmcBaseline, 18);
store.generateForecast(id);
assert.equal(store.contract.getDailyForecast(id, child.childId, date).pmcBaseline, 18, 'recompute does not compound or erase calibration');
store.calibrateBaseline(id, 'child', child.childId, { mode: 'ratio', value: 25 }, '子体单独校准');
assert.equal(store.getCurrent().childForecastResults[0].dailyFinalForecast[date], 15);
store.calibrateBaseline(id, 'child', child.childId, null, '撤销子体校准');
assert.equal(store.getCurrent().childForecastResults[0].dailyFinalForecast[date], 18);
store.calibrateBaseline(id, 'parent', parent.key, null, '撤销父体校准');
assert.equal(store.getCurrent().childForecastResults[0].dailyFinalForecast[date], original);
assert.throws(() => store.calibrateBaseline(id, 'parent', parent.key, { mode: 'ratio', value: -101 }, '非法输入'));
const dates = Object.keys(parent.daily);
const statuses = { [dates[0]]: values.waiting, [dates[1]]: values.waiting };
const daily = Object.fromEntries(dates.map(d => [d, statuses[d] ? null : 20]));
const beforeInvalidImport = store.getCurrent();
assert.throws(() => store.importDailyModelResults(id, parent.key, daily, { ...statuses, [dates[2]]: '未知状态' }, '非法状态'));
assert.throws(() => store.importDailyModelResults(id, parent.key, { ...daily, [dates[0]]: 10 }, statuses, '状态数值冲突'));
assert.deepEqual(store.getCurrent(), beforeInvalidImport, 'invalid import must not change batch or audit');
store.importDailyModelResults(id, parent.key, daily, statuses, '上游日级结果V2');
batch = store.getCurrent();
assert.equal(batch.childForecastResults[0].dailyFinalForecast[date], null);
assert.equal(batch.childForecastResults[0].dailyForecastStatus[date], values.waiting);
assert.equal(values.sum([null, null]), null);
assert.equal(values.sum([null, 4, 6]), 10);
store.calibrateBaseline(id, 'parent', parent.key, { mode: 'adu', value: 40 }, '有数值日期校准');
store.generateForecast(id); store.confirmForecast(id);
const waiting = store.contract.getDailyForecast(id, child.childId, date);
assert.equal(waiting.pmcBaseline, null); assert.equal(waiting.systemForecast, null); assert.equal(waiting.forecastStatus, values.waiting);
assert.equal(store.contract.getDailyForecast(id, child.childId, dates[2]).pmcBaseline, 24);
const rows = store.contract.getSubmissionRows(id);
assert(rows.filter(row => row.forecastStatus).every(row => row.pmcBaseline === null && row.systemForecast === null));
store.publishWindow(id, batch.submissionWindow);
assert.throws(() => store.calibrateBaseline(id, 'parent', parent.key, { mode: 'adu', value: 10 }, '不能修改已发布快照'), /已发布/);
assert.throws(() => store.generateForecast(id), /已发布/);
store.freeze(id);
assert.equal(store.getCurrent().status, '已冻结');
assert(firstSnapshot, 'previous snapshot remains available');
console.log('Role baseline, restore, recompute, publication lock and nonnumeric forecast tests passed');
